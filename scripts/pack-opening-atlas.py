#!/usr/bin/env python3
"""Package existing menu art only. No resizing, compositing, color or alpha edits.

Requires Pillow with WebP. --check verifies every decoded RGBA byte, including
RGB under zero alpha, source hashes, manifest and reproducible generated CSS.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/client/app/ui/opening-atlas'
SIEGE = 'src/client/app/ui/siege/'
items = {}
def source(name, path):
    image = Image.open(ROOT / path).convert('RGBA')
    items[name] = (image, path)

for name, path in {
    'phone-rest': 'button-steel-rest.webp', 'phone-pressed': 'button-steel-pressed.webp',
    **{f'desk-{s}': f'button-steel-desk-{s}.webp' for s in ('rest','hover','focus','pressed','disabled')},
    **{f'search-{s}': f'search-button-{s}.webp' for s in ('rest','hover','focus','pressed','disabled')},
    'search-header': 'search-header.webp', 'search-body': 'search-body.webp', 'search-count': 'search-count.webp',
}.items(): source(name, SIEGE + path)
# Existing HTML delivery variants; retain their decoded pixels without resampling.
for name, path in {'gate':'gate-1536.webp', 'title':'cassette-title-1120.webp',
                   'frame':'frame-667.webp', 'chain':'chain-tile-160.webp',
                   'eyelet':'eyelet-90.webp'}.items():
    source(name, 'src/client/app/ui/delivery/' + path)
for side in ('white', 'black'):
    for endpoint in ('00','55'):
        source(f'{side}-{endpoint}', f'src/client/modules/board/selection-v2/frames/{side}/{side}-{endpoint}.webp')

# Deterministic shelf packing; a 2px exact edge extrusion prevents filtering from
# sampling adjacent art. Source rectangles themselves remain entirely unmodified.
width = 4096
frames, provenance = {}, {}
x = y = row = 0
for name, (im, path) in sorted(items.items(), key=lambda item: (-item[1][0].height, item[0])):
    w,h = im.size
    if x + w + 4 > width: x = 0; y += row; row = 0
    frames[name] = [x+2,y+2,w,h]
    provenance[name] = {'source':path, 'sha256':hashlib.sha256((ROOT/path).read_bytes()).hexdigest(), 'rgbaSha256':hashlib.sha256(im.tobytes()).hexdigest()}
    x += w + 4; row = max(row, h+4)
height = y + row
atlas = Image.new('RGBA', (width,height))
for name, (im, _) in items.items():
    x,y,w,h = frames[name]
    atlas.paste(im,(x,y)) # never use an alpha mask (would premultiply alpha)
    for offset in (1,2):
        atlas.paste(im.crop((0,0,1,h)),(x-offset,y))
        atlas.paste(im.crop((w-1,0,w,h)),(x+w-1+offset,y))
        atlas.paste(im.crop((0,0,w,1)),(x,y-offset))
        atlas.paste(im.crop((0,h-1,w,h)),(x,y+h-1+offset))
    for dx,sx in ((-2,0),(w,w-1)):
        for dy,sy in ((-2,0),(h,h-1)):
            atlas.paste(im.crop((sx,sy,sx+1,sy+1)).resize((2,2),Image.Resampling.NEAREST),(x+dx,y+dy))

def sub(name, parent, box):
    x,y,_,_ = frames[parent]; l,t,r,b = box
    frames[name] = [x+l,y+t,r-l,b-t]
    provenance[name] = {'parent':parent,'crop':[l,t,r,b]}

def nine(name, left, top, right, bottom):
    _,_,w,h = frames[name]
    xs=[0,left,w-right,w];ys=[0,top,h-bottom,h]
    for row in range(3):
        for col in range(3): sub(f'{name}-{row*3+col}',name,(xs[col],ys[row],xs[col+1],ys[row+1]))
nine('frame',180,180,180,180)
for state in ('rest','hover','focus','pressed','disabled'): nine('search-'+state,48,40,48,40)
nine('search-body',90,0,90,90)
nine('search-count',20,12,20,12)
sub('backplate-left','gate',(245,270,645,730))
sub('backplate-right','gate',(890,270,1290,730))
manifest={'size':[width,height],'frames':frames,'provenance':provenance}

# Percent positions solve (container - scaled atlas) * position = -scaled origin.
# Each slice scales independently with its grid cell; corners have fixed CSS size.
def rule(selector, name):
    x,y,w,h=frames[name]
    if not w or not h: return f'{selector}{{background:none}}\n'
    return f'{selector}{{background-size:{width/w*100:.10f}% {height/h*100:.10f}%;background-position:{x/(width-w)*100:.10f}% {y/(height-h)*100:.10f}%}}\n'
css = '''/* Generated by scripts/pack-opening-atlas.py from atlas.json. Do not hand edit. */
#opening .atlas-slice { background-image:url('./atlas.webp'); background-image:image-set(url('./atlas.webp') type('image/webp'), url('./atlas.avif') type('image/avif')); background-repeat:no-repeat; opacity:1; }
#opening .atlas-nine { position:absolute; inset:0; display:grid; grid-template-columns:var(--slice-x) minmax(0,1fr) var(--slice-x); grid-template-rows:var(--slice-y) minmax(0,1fr) var(--slice-y); pointer-events:none; z-index:-1; }
#opening .atlas-nine > i { display:block; min-width:0; min-height:0; }
#opening .chronicle-frame { --slice-x:var(--frame-corner); --slice-y:var(--frame-corner); }
#opening .chronicle-right .chronicle-frame { transform:scaleX(-1); }
#opening .chronicle-backplate { position:absolute; inset:8px; z-index:-2; box-shadow:0 6px 8px #0009; }
#opening .siege-housing > span { position:absolute; width:max(100vw,150vh); height:auto; aspect-ratio:3/2; left:50%; top:50%; translate:-50% -50%; }
#opening .gate-piece { position:absolute; width:var(--piece); height:var(--piece); left:50%; top:0; translate:-50% 0; }
#opening .chronicle-chain { background:none; }
#opening .chain-links { position:absolute; inset:0; display:flex; justify-content:flex-end; overflow:hidden; }
#opening .chronicle-right .chain-links { justify-content:flex-start; }
#opening .chain-links i { display:block; flex:0 0 calc(20px * 139 / 105); height:20px; }
#opening .chronicle-chain::after { background:none; }
#opening .chain-eyelet { position:absolute; width:30px; height:calc(30px * 339 / 303); right:-10px; top:-7px; transform:scaleX(-1); }
#opening .chronicle-right .chain-eyelet { right:auto; left:-10px; transform:none; }
#opening .menu-button-art { position:absolute; inset:0; pointer-events:none; z-index:-1; }
#opening :is(#opening-play,#opening-online,#opening-retry,#opening-history,#opening-options) { isolation:isolate; background:none; }
#opening .search-body-art { --slice-x:24px; --slice-y:24px; grid-template-rows:0 minmax(0,1fr) 24px; }
#opening .search-count-art { --slice-x:10px; --slice-y:4px; }
#opening .search-button-art { --slice-x:24px; --slice-y:20px; }
#opening-search-actions button, #opening-online-count { isolation:isolate; }
#opening .friend-code-frame { position:relative; isolation:isolate; flex:1 1 100%; width:100%; min-width:0; height:var(--btn-h); }
#opening .friend-code-frame:has(input[hidden]) { display:none; }
#opening .friend-code-frame .chronicle-frame { --slice-x:14px; --slice-y:14px; }
#opening #opening-friend-code { border-image:none; background:none; height:100%; }
'''
# The opaque gate rectangle doubles as a CSS-only coverage mask: before decode
# only the solid #opening background paints, then labels and all slices paint
# together. No timer, opacity animation, image callbacks or font readiness gate.
gx, gy, gw, gh = frames['gate']
assert items['gate'][0].getchannel('A').getextrema() == (255, 255)
css += f"#opening .opening-sheet {{ mask-image:url('./atlas.webp'); mask-image:image-set(url('./atlas.webp') type('image/webp'), url('./atlas.avif') type('image/avif')); mask-mode:alpha; mask-repeat:no-repeat; mask-size:{width/gw*100:.10f}% {height/gh*100:.10f}%; mask-position:{gx/(width-gw)*100:.10f}% {gy/(height-gh)*100:.10f}%; }}\n"
for sel,name in [('.siege-housing > span','gate'),('.siege-cartouche','title'),('.chronicle-left .chronicle-backplate','backplate-left'),('.chronicle-right .chronicle-backplate','backplate-right'),('.chain-links i','chain'),('.chain-eyelet','eyelet'),('.opening-search-plate','search-header')]: css+=rule('#opening '+sel,name)
for side in ('white','black'):
    for pressed,frame in (('false','00'),('true','55')):
        css+=rule(f'#opening [data-side="{side}"][aria-pressed="{pressed}"] .gate-piece',f'{side}-{frame}')
for name,selector in [('frame','.chronicle-frame'),('search-body','.search-body-art'),('search-count','.search-count-art')]:
    for i in range(9): css+=rule(f'#opening {selector} > i:nth-child({i+1})',f'{name}-{i}')
for state,pseudo in [('rest',''),('hover',':hover:not(:disabled)'),('focus',':focus-visible:not(:disabled)'),('pressed',':active:not(:disabled)'),('disabled',':disabled')]:
    for i in range(9): css+=rule(f'#opening #opening-search-actions button{pseudo} .search-button-art > i:nth-child({i+1})',f'search-{state}-{i}')
selector='#opening :is(#opening-play,#opening-online,#opening-retry,#opening-history,#opening-options)'
css+=rule(selector+' .menu-button-art','phone-rest')
css+=rule(selector+':active:not(:disabled) .menu-button-art','phone-pressed')
css+='@media(min-width:970px) and (min-height:501px) {\n'
css+=selector+' { container-type:size; }\n'
css+='#opening .menu-button-art { inset:auto; left:50%; top:50%; translate:-50% -50%; width:min(100cqw,calc(100cqh * 1344 / 294)); height:min(100cqh,calc(100cqw * 294 / 1344)); }\n'
for state,pseudo in [('rest',''),('hover',':hover:not(:disabled)'),('focus',':focus-visible:not(:disabled)'),('pressed',':active:not(:disabled)'),('disabled',':disabled')]: css+=rule(selector+pseudo+' .menu-button-art','desk-'+state)
css+='}\n'

parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');parser.add_argument('--css-only',action='store_true');args=parser.parse_args()
if args.check:
    assert json.loads((OUT/'atlas.json').read_text())==manifest, 'Manifest stale'
    assert (OUT/'atlas.css').read_text()==css, 'Generated CSS stale'
else:
    OUT.mkdir(exist_ok=True)
    if not args.css_only: atlas.save(OUT/'atlas.webp',lossless=True,exact=True,method=6)
    (OUT/'atlas.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    (OUT/'atlas.css').write_text(css)
decoded=Image.open(OUT/'atlas.webp').convert('RGBA')
assert decoded.size==atlas.size
assert decoded.tobytes()==atlas.tobytes(), 'Atlas RGBA mismatch (including transparent RGB)'
for name,(im,_) in items.items():
    x,y,w,h=frames[name]
    assert decoded.crop((x,y,x+w,y+h)).tobytes()==im.tobytes(), name
if (OUT/'atlas.avif').exists():
    avif = Image.open(OUT/'atlas.avif').convert('RGBA')
    assert avif.size == atlas.size and avif.tobytes() == atlas.tobytes(), 'AVIF candidate RGBA mismatch'
    print(f'AVIF candidate exact RGBA verified: {(OUT/"atlas.avif").stat().st_size} bytes (WebP preferred).')
print(f'Exact RGBA verified: {len(items)} sources, {len(frames)} frames, {width}x{height}, {(OUT/"atlas.webp").stat().st_size} bytes; generated CSS matches manifest.')
