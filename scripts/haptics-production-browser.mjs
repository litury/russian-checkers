// Unmodified production bundle; only the device API is replaced with a spy.
import { chromium } from '/home/hermes/.hermes/team/studio/browser-tools/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await chromium.launch({executablePath:'/usr/local/bin/google-chrome',headless:true,args:['--no-sandbox']});
try {
 const context = await browser.newContext({viewport:{width:390,height:844}});
 await context.route('**/*',route => /^http:\/\/127\.0\.0\.1:4231\//.test(route.request().url()) ? route.continue() : route.abort());
 await context.addInitScript(() => {
  localStorage.setItem('checkers.menuVibration','true'); localStorage.setItem('checkers.autoMove','0');
  window.hapticCalls=[];
  Object.defineProperty(navigator,'vibrate',{configurable:true,writable:true,value:pattern=>{window.hapticCalls.push(pattern);return true;}});
 });
 const page=await context.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4231/');
 await page.waitForFunction(()=>document.querySelector('#opening')?.dataset.menuState==='ready');
 const white=page.locator('.gate-piece-slot[data-side="white"]');
 const black=page.locator('.gate-piece-slot[data-side="black"]');
 await white.click(); await white.focus();
 const keyboardResults=[];
 const checkKey=async(key,side,expected)=>{
  await page.evaluate(()=>{window.hapticCalls=[];});
  await page.keyboard.press(key);
  assert.equal(await page.locator(`.gate-piece-slot[data-side="${side}"]`).getAttribute('aria-pressed'),'true');
  const calls=await page.evaluate(()=>window.hapticCalls);
  assert.deepEqual(calls,expected); keyboardResults.push({key,side,calls});
 };
 await checkKey('ArrowRight','black',[10]);
 await checkKey('ArrowLeft','white',[10]);
 await checkKey('ArrowDown','black',[10]);
 await checkKey('ArrowUp','white',[10]);
 await checkKey('End','black',[10]);
 await checkKey('End','black',[]);
 await checkKey('Home','white',[10]);
 await checkKey('Home','white',[]);
 await black.evaluate(el=>{el.disabled=true;});
 await checkKey('ArrowRight','white',[]);
 await black.evaluate(el=>{el.disabled=false;});
 await white.evaluate(el=>{el.setAttribute('aria-disabled','true');});
 await checkKey('End','white',[]);
 await white.evaluate(el=>{el.removeAttribute('aria-disabled'); el.addEventListener('keydown',event=>event.preventDefault(),{capture:true,once:true});});
 await checkKey('End','white',[]);
 await page.evaluate(()=>{window.hapticCalls=[];});
 await black.click();
 assert.deepEqual(await page.evaluate(()=>window.hapticCalls),[10]);
 await white.click();
 await page.click('#opening-play');
 await page.waitForFunction(()=>document.querySelector('#game canvas')?.tabIndex===0 && document.querySelector('#opening').hidden);
 await page.waitForTimeout(600);
 await page.evaluate(()=>{window.hapticCalls=[];});
 await page.locator('#game canvas').focus();
 await page.keyboard.press('Enter');
 assert.deepEqual(await page.evaluate(()=>window.hapticCalls),[10]);
 await page.keyboard.press('ArrowUp'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('Enter');
 await page.waitForTimeout(300);
 assert.deepEqual(await page.evaluate(()=>window.hapticCalls),[10,15]);
 assert.deepEqual(errors,[]);
 const result={productionBundleUnmodified:true,keyboardResults,calls:await page.evaluate(()=>window.hapticCalls),label:await page.locator('#game canvas').getAttribute('aria-label'),errors,physicalVibrationTested:false};
 await fs.writeFile('docs/haptics-evidence/production-results.json',JSON.stringify(result,null,2));
 await page.screenshot({path:'docs/haptics-evidence/production-move.png'});
 console.log(result);
}finally{await browser.close();}
